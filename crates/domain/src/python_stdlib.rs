/// Whether `name` is the name of a module of Python's standard library in any version from 3.10 to 3.14, a top-level
/// one (`os`, not `os.path`).
pub fn is_standard_library(name: &str) -> bool {
    STANDARD_LIBRARY.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_names_are_in_byte_order_without_repeats_so_that_a_search_finds_each() {
        assert!(STANDARD_LIBRARY.windows(2).all(|pair| pair[0] < pair[1]));
        for name in STANDARD_LIBRARY {
            assert!(is_standard_library(name), "{name}");
        }
    }

    #[test]
    fn a_name_of_any_version_from_3_10_to_3_14_is() {
        for name in [
            // In all of them
            "queue",
            "string",
            "os",
            "json",
            "types",
            "cProfile",
            "__future__",
            // Dropped before 3.14, 3.13, 3.12, and added in 3.11 and 3.14
            "distutils",
            "telnetlib",
            "asyncore",
            "tomllib",
            "annotationlib",
        ] {
            assert!(is_standard_library(name), "{name}");
        }
    }

    #[test]
    fn a_name_that_is_no_module_of_it_is_not() {
        // A name of a unit, a dotted name (a module of a package is not a top-level one) and one in another case
        for name in [
            "billing",
            "core",
            "domain",
            "os.path",
            "Queue",
            "",
            "numpy",
            "profiling",
        ] {
            assert!(!is_standard_library(name), "{name}");
        }
    }
}
