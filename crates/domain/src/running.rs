//! How to run Rotproof, `.rotproof/running.md`, which `rotproof create` writes and `rotproof check` compares, as it
//! does the guide `.rotproof/AGENTS.md`. The guide holds the rules every session needs; this page holds how to upgrade
//! Rotproof and when to run which command, which an agent needs only then, so the guide names it in one line and the
//! agent reads it when it upgrades or runs a command. It judges what the commands print and never says which command
//! comes next: `rotproof check` and `rotproof init` say that, and a second place that did would drift from them.
//!
//! It is written to `.rotproof/` alone, beside the guide, and to no place an agent loads by itself (a directory of
//! skills): whether an agent reads Rotproof's text is the project's choice, made by the line that points it at the
//! guide.
//!
//! The text is in `project/rotproof/`, built into the binary. It is the same for every project, whatever its stack, and
//! it carries no version: the project's `files` says which version wrote it, and a project upgrades through
//! `rotproof init` as for the guide.

/// The text of the page, as it is written to [`PATH`].
pub const RUNNING: &str = include_str!("../../../project/rotproof/running.md.in");

/// Where the page is written, from the root.
pub const PATH: &str = ".rotproof/running.md";

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_page_is_one_text_with_nothing_for_a_tool_to_load_it_by() {
        // No frontmatter: nothing loads it as a skill, so a name and a description would be read by no one
        assert!(
            RUNNING.starts_with("<!-- Generated by `rotproof create`."),
            "{RUNNING}"
        );
        assert!(RUNNING.contains("\n# Running Rotproof\n"));
        assert!(!RUNNING.contains("{version}") && !RUNNING.contains("{stack}"));
        assert!(!RUNNING.contains('\r'));
    }

    #[test]
    fn the_page_names_every_command_that_runs_in_a_session_and_none_that_is_gone() {
        for command in [
            "check", "init", "create", "index", "follows", "new", "log", "guide",
        ] {
            assert!(
                RUNNING.contains(&format!("`rotproof {command}")),
                "{command}"
            );
        }
        for gone in ["stop-hook", "time-hook", "--reviewed"] {
            assert!(!RUNNING.contains(gone), "{gone}");
        }
    }
}
