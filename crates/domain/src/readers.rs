//! Who reads each shared unit: `.rotproof/readers.md`, which `rotproof index` and `rotproof create` write from the
//! imports of the code and `rotproof check` compares with what they would write now.
//!
//! A shared unit is a part that any unit may import, and nothing stops it from collecting what no one needs. The file
//! lists, for each shared unit in the order the project declares them, the names that the other units import of it
//! and the units that import each, by their names alone (no file is named, so a change of a line moves nothing in
//! it). A name that exactly one unit reads is listed apart, so that what a shared unit holds for a single reader
//! stands out, and a new one shows in a diff. No rule fails for it: a library that one unit uses may be shared on
//! purpose.
//!
//! What a name is depends on what the language imports, and is given by the reader (`application`): in Python the
//! dotted module as resolved (`from m import n` is `m.n`); in TypeScript the path the import lands in, from the root
//! and without its extension, with `: name` for each name the import takes; in Rust the path a crate writes through its
//! dependency on a crate of the unit (`core_domain::score::count`), a whole module imported being the module.

use std::collections::{BTreeMap, BTreeSet};

use crate::direction::Landing;
use crate::layers::Place;
use crate::units::Unit;

/// Where the list is, from the root
pub const FILE: &str = ".rotproof/readers.md";

/// What `rotproof check` says when the list is not what Rotproof writes now
pub const HEADING: &str = "the readers of each shared unit are listed in .rotproof/readers.md";

/// What the file says of a unit that no other unit reads
const NONE: &str = "Read by no unit.";

/// One name of a shared unit, read by one unit.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Read {
    /// The name of the shared unit that is read
    pub unit: String,
    /// What is read, as the reader names it
    pub name: String,
    /// The name of the unit that reads it
    pub by: String,
}

/// The read of `name`, by a file that sits in `from`, when it lands in a place of a shared unit other than its own. An
/// import of a unit's code outside its layers is no read of a name: it fails by the rules between units.
pub fn read_of<'a>(from: &Place, to: impl Into<Landing<'a>>, name: &str) -> Option<Read> {
    match to.into() {
        Landing::Place(to) if to.unit.shared && to.unit.name != from.unit.name => Some(Read {
            unit: to.unit.name.clone(),
            name: name.to_string(),
            by: from.unit.name.clone(),
        }),
        _ => None,
    }
}

/// The text of `.rotproof/readers.md` for the shared units among `units` and what `reads` found, or `None` when no
/// unit is shared and the file is not written (nor is one there).
pub fn render(units: &[Unit], reads: &[Read]) -> Option<String> {
    let shared: Vec<&Unit> = units.iter().filter(|unit| unit.shared).collect();
    if shared.is_empty() {
        return None;
    }
    let mut text = String::from(
        "<!-- Generated by `rotproof index` from the imports of the code: do not edit. -->\n\
         # Who reads the shared units\n\
         \n\
         The names that other units import of each shared unit, with the units that read each. A name that exactly one \
         unit reads is listed apart.\n",
    );
    for unit in shared {
        let mut names: BTreeMap<&str, BTreeSet<&str>> = BTreeMap::new();
        for read in reads.iter().filter(|read| read.unit == unit.name) {
            names.entry(&read.name).or_default().insert(&read.by);
        }
        let many: Vec<_> = names.iter().filter(|(_, by)| by.len() > 1).collect();
        let one: Vec<_> = names.iter().filter(|(_, by)| by.len() == 1).collect();
        let path = if unit.path.is_empty() {
            "."
        } else {
            &unit.path
        };
        text.push_str(&format!("\n## {}\n\n`{path}`\n", unit.name));
        if names.is_empty() {
            text.push_str(&format!("\n{NONE}\n"));
            continue;
        }
        if !many.is_empty() {
            text.push_str(&table(&many));
        }
        if !one.is_empty() {
            text.push_str("\n### Read by one unit\n");
            text.push_str(&table(&one));
        }
    }
    Some(text)
}

/// A table of names and the units that read them, in the order given.
fn table(rows: &[(&&str, &BTreeSet<&str>)]) -> String {
    let mut text = String::from("\n| Name | Read by |\n|---|---|\n");
    for (name, by) in rows {
        let by: Vec<&str> = by.iter().copied().collect();
        text.push_str(&format!(
            "| `{}` | {} |\n",
            name.replace('|', "\\|"),
            by.join(", ")
        ));
    }
    text
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::layers::UnitTag;

    fn unit(name: &str, path: &str, shared: bool) -> Unit {
        Unit {
            name: name.into(),
            path: path.into(),
            root: path.into(),
            shared,
            entries: Vec::new(),
            absent: Vec::new(),
            declared: true,
        }
    }

    fn read(unit: &str, name: &str, by: &str) -> Read {
        Read {
            unit: unit.into(),
            name: name.into(),
            by: by.into(),
        }
    }

    #[test]
    fn nothing_is_written_when_no_unit_is_shared() {
        let units = [unit("billing", "billing", false)];
        assert_eq!(render(&units, &[]), None);
        assert_eq!(render(&[], &[]), None);
        // What was read of a unit that is not shared is no one's business here
        assert_eq!(render(&units, &[read("billing", "billing.x", "cli")]), None);
    }

    #[test]
    fn the_list_has_the_shared_units_in_the_order_declared_and_the_names_in_byte_order_by_unit_name_alone()
     {
        let units = [
            unit("steps", "packages/steps/src/steps", true),
            unit("billing", "billing", false),
            unit("core", "", true),
        ];
        let reads = [
            read("core", "core.domain.b", "web"),
            read("core", "core.domain.b", "billing"),
            read("core", "core.domain.b", "web"),
            read("core", "core.domain.a", "billing"),
            read("core", "core.domain.a", "web"),
            read("core", "Z", "web"),
            read("core", "Z", "billing"),
            read("core", "core.solo", "web"),
            read("core", "core.only", "billing"),
            // What is read of a unit that is not shared is not listed
            read("billing", "billing.x", "web"),
        ];
        let text = render(&units, &reads).unwrap();
        assert_eq!(
            text,
            "<!-- Generated by `rotproof index` from the imports of the code: do not edit. -->
# Who reads the shared units

The names that other units import of each shared unit, with the units that read each. A name that exactly one unit reads is listed apart.

## steps

`packages/steps/src/steps`

Read by no unit.

## core

`.`

| Name | Read by |
|---|---|
| `Z` | billing, web |
| `core.domain.a` | billing, web |
| `core.domain.b` | billing, web |

### Read by one unit

| Name | Read by |
|---|---|
| `core.only` | billing |
| `core.solo` | web |
"
        );
        // The same in any order the reads come in
        let mut backwards = reads.to_vec();
        backwards.reverse();
        assert_eq!(render(&units, &backwards), Some(text));
    }

    #[test]
    fn only_one_reader_each_lists_the_section_alone_and_a_pipe_in_a_name_is_escaped() {
        let units = [unit("core", "core", true)];
        let text = render(&units, &[read("core", "a: b|c", "web")]).unwrap();
        assert!(
            text.ends_with(
                "## core\n\n`core`\n\n### Read by one unit\n\n| Name | Read by |\n|---|---|\n| `a: b\\|c` | web |\n"
            ),
            "{text}"
        );
        assert!(!text.contains("Read by no unit."));
    }

    #[test]
    fn a_read_is_a_name_of_a_place_of_a_shared_unit_by_another_unit() {
        let place = |name: &str, shared: bool| Place {
            name: "domain".into(),
            path: format!("{name}/domain"),
            parent: None,
            role: String::new(),
            imports: Vec::new(),
            below: Vec::new(),
            files: Vec::new(),
            unit: UnitTag {
                name: name.into(),
                shared,
                app: false,
            },
        };
        let (from, core, own) = (
            place("billing", false),
            place("core", true),
            place("billing", true),
        );
        let found = read_of(&from, Landing::Place(&core), "core.x").unwrap();
        assert_eq!(found, read("core", "core.x", "billing"));
        // Not another unit's place, not shared, nor the code of a unit outside its layers
        assert_eq!(read_of(&from, Landing::Place(&from), "x"), None);
        assert_eq!(read_of(&core, Landing::Place(&from), "x"), None);
        assert_eq!(read_of(&own, Landing::Place(&own), "x"), None);
        let outside = unit("core", "core", true);
        assert_eq!(read_of(&from, Landing::InUnit(&outside), "x"), None);
    }
}
